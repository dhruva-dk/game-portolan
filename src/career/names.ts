export type SponsorName = { name: string; emblem: number };

const capital = (word: string): string =>
  word.charAt(0).toUpperCase() + word.slice(1);

export function nameAt(seed: string, id: number, attempt: number): string {
  const part = (table: readonly string[], field: string): string =>
    pick(table, seed, 'person', id, 'name', field, attempt);
  const initial = part(GIVEN_START, 'given').charAt(0).toUpperCase();
  const family = part(FAMILY_START, 'start') + part(FAMILY_END, 'end');
  return `${initial}. ${capital(family)}`;
}

export function personName(
  seed: string,
  id: number,
  accepts: (name: string) => boolean = allowed
): string {
  for (let attempt = 0; ; attempt++) {
    const name = nameAt(seed, id, attempt);
    if (accepts(name)) return name;
  }
}

